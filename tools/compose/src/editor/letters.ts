/** Lit cells of one character as [column, row] pairs. Throws for characters the alphabet lacks. */
export function litCells(character: string): [number, number][] {
  const rows = cells[character];
  if (!rows) throw new Error(`No 5x7 cells for ${JSON.stringify(character)}`);
  return rows.flatMap((row, y) => [...row].flatMap((on, x) => (on === '1' ? [[x, y] as [number, number]] : [])));
}

/** Width of a character in cells (five, or one for the colon). */
export const cellColumns = (character: string): number => cells[character]?.[0].length ?? 5;
